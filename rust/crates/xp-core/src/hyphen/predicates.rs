pub(super) fn latin(cp: u32) -> bool {
    matches!(cp, 0x41..=0x5a | 0x61..=0x7a | 0xc0..=0xd6 | 0xd8..=0xf6 | 0xf8..=0x17f | 0x1e9e)
}
pub(super) fn cyrillic(cp: u32) -> bool {
    (0x400..=0x52f).contains(&cp)
}
pub(super) fn alphabetic(cp: u32) -> bool {
    latin(cp) || cyrillic(cp)
}
pub(super) fn lower(cp: u32, cyr: bool) -> u32 {
    if cyr {
        return match cp {
            0x410..=0x42f => cp + 0x20,
            0x401 => 0x451,
            _ => cp,
        };
    }
    match cp {
        0x41..=0x5a => cp + 0x20,
        0xc0..=0xd6 | 0xd8..=0xde => cp + 0x20,
        0x100..=0x137 | 0x14a..=0x177 if cp & 1 == 0 => cp + 1,
        0x139..=0x148 | 0x179..=0x17e if cp & 1 != 0 => cp + 1,
        0x178 => 0xff,
        0x1e9e => 0xdf,
        _ => cp,
    }
}
pub(super) fn punctuation(cp: u32) -> bool {
    matches!(cp, 0x2d | 0x2e | 0x2c | 0x21 | 0x3f | 0x3b | 0x3a | 0x22 | 0x27 | 0x29 | 0x28 | 0xab | 0xbb | 0x2018..=0x201a | 0x201c..=0x201e | 0xa0 | 0x7b | 0x7d | 0x5b | 0x5d | 0x2f | 0x2039 | 0x203a | 0x2026)
}
pub(super) fn apostrophe(cp: u32) -> bool {
    matches!(cp, 0x27 | 0x2018 | 0x2019)
}
pub(super) fn explicit(cp: u32) -> bool {
    matches!(
        cp,
        0x2d | 0xad | 0x58a | 0x2010
            ..=0x2015
                | 0x2043
                | 0x207b
                | 0x208b
                | 0x2212
                | 0x2e17
                | 0x2e3a
                | 0x2e3b
                | 0xfe58
                | 0xfe63
                | 0xff0d
                | 0x5f
                | 0x2026
    )
}
pub(super) fn separator(cp: u32) -> bool {
    explicit(cp) || apostrophe(cp)
}
pub(super) fn cjk(cp: u32) -> bool {
    matches!(cp, 0x1100..=0x11ff | 0x3000..=0x30ff | 0x3130..=0x318f | 0x3400..=0x4dbf | 0x4e00..=0x9fff | 0xac00..=0xd7ff | 0xf900..=0xfaff | 0xfe30..=0xfe4f | 0xff01..=0xff60 | 0xff65..=0xffef | 0x20000..=0x2a6df | 0x2a700..=0x2b73f)
}
