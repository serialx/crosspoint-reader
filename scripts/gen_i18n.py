def generate_keys_header(
    languages: List[str],
    language_names: List[str],
    language_bcp47: List[str],
    string_keys: List[str],
    output_path: str,
    verbose: bool = False,
    builtin: Optional[Set[str]] = None,
) -> None:
    """Generate I18nKeys.h.

    Every language keeps its enum value, code and name, so code that names a
    language (keyboard layouts, the V1 migration table) compiles either way.
    Only built-in languages get string tables and appear in the picker.
    """
    compiled = [c for c in languages if builtin is None or c in builtin]
    lines: List[str] = [
        "#pragma once",
        "#include <cstdint>",
        "",
        AUTO_GENERATED_COMMENT,
        CLANG_FORMAT_OFF_COMMENT,
        "",
    ]

    # Language enum
    lines.append("// Language enum (ordered by _bcp47, English first)")
    lines.append("enum class Language : uint8_t {")
    code_width = max(len(lang) for lang in languages)
    for i, (lang, bcp47) in enumerate(zip(languages, language_bcp47)):
        lines.append(f"  {lang:<{code_width}} = {i},  // {bcp47}")
    lines.append("  _COUNT")
    lines.append("};")
    lines.append("")

    # Extern declarations
    lines.append("// Language metadata (defined by Rust)")
    lines.append('extern "C" {')
    lines.append("extern const char* const LANGUAGE_CODES[];")
    lines.append("")

    lines.append("extern const char* const LANGUAGE_NAMES[];")
    lines.append("")
    lines.append("extern const char* const CHARACTER_SETS[];")
    lines.append("}")
    lines.append("")

    # StrId enum
    lines.append("// String IDs")
    lines.append("enum class StrId : uint16_t {")
    for key in string_keys:
        lines.append(f"  {key},")
    lines.append("  // Sentinel - must be last")
    lines.append("  _COUNT")
    lines.append("};")
    lines.append("")

    # getLanguageCount helper (single line to match checked-in format)
    lines.append("// Helper function to get language count")
    lines.append(
        "constexpr uint8_t getLanguageCount() "
        "{ return static_cast<uint8_t>(Language::_COUNT); }"
    )
    lines.append("")

    # Sorted language indices for display order
    # (English first, then by _bcp47 tag alphabetically)
    english_idx = languages.index("EN")
    rest = sorted(
        (i for i in range(len(languages)) if i != english_idx and languages[i] in compiled),
        key=lambda i: language_bcp47[i],
    )
    sorted_indices = [english_idx] + rest
    lines.append("// Sorted language indices by _bcp47 (auto-generated by gen_i18n.py)")
    for rank, idx in enumerate(sorted_indices):
        lines.append(f"//   {rank:>2}: {languages[idx]:<4} {language_bcp47[idx]:<8} {language_names[idx]}")
    lines.append(
        "constexpr uint8_t SORTED_LANGUAGE_INDICES[] = {"
        f"{', '.join(str(i) for i in sorted_indices)}"
        "};"
    )
    lines.append("")
    size_check = "==" if builtin is None else "<="
    lines.append(
        f"static_assert(sizeof(SORTED_LANGUAGE_INDICES) / sizeof(SORTED_LANGUAGE_INDICES[0]) {size_check} getLanguageCount(),"
    )
    lines.append('              "SORTED_LANGUAGE_INDICES size mismatch");')
    lines.append("")

    # V1 language.bin migration table -- frozen enum order from commit 2f969a9.
    # Maps the old uint8_t index stored on disk to the current Language enum.
    # If a Language enum value listed here is ever removed, this will fail to
    # compile, signalling that the migration table needs updating.
    v1_codes = [
        "EN", "ES", "FR", "DE", "CS", "PT", "RU", "SV", "RO", "CA", "UK",
        "BE", "IT", "PL", "FI", "DA", "NL", "TR", "KK", "HU", "LT", "SI",
    ]
    lines.append("// V1 language.bin migration table (frozen enum order from 2f969a9)")
    lines.append("constexpr Language V1_LANGUAGES[] = {")
    lines.append("    " + ", ".join(f"Language::{c}" for c in v1_codes) + ",")
    lines.append("};")
    lines.append(
        f"constexpr uint8_t V1_LANGUAGE_COUNT = {len(v1_codes)};"
    )

    _write_file(output_path, lines, verbose)


def _rust_literal(text: str, c_string: bool = False) -> str:
    # Preserve the existing generator's C escape interpretation, including
    # escaped backslashes, before writing unambiguous Rust byte escapes.
    data = codecs.escape_decode("".join(escape_cpp_string(text)).encode("ascii"))[0]
    escaped = "".join(f"\\x{byte:02x}" for byte in data)
    return 'c"' + escaped + '"' if c_string else 'b"' + escaped + '\\x00"'


def generate_rust(
    languages: List[str],
    language_names: List[str],
    string_keys: List[str],
    translations: Dict[str, List[str]],
    output_path: str,
    verbose: bool = False,
    builtin: Optional[Set[str]] = None,
) -> None:
    """Emit immutable packed tables; bit 15 selects the English blob."""
    compiled = [c for c in languages if builtin is None or c in builtin]
    lines = [AUTO_GENERATED_COMMENT, "",
             f"pub const LANGUAGE_COUNT: u8 = {len(languages)};",
             f"pub const STRING_COUNT: usize = {len(string_keys)};", ""]
    lines += ["pub mod ids {"] + [
        f"    pub const {key}: u16 = {i};" for i, key in enumerate(string_keys)
    ] + ["}", ""]
    for symbol, values in [
        ("LANGUAGE_CODES", languages),
        ("LANGUAGE_NAMES", language_names),
        ("CHARACTER_SETS", [compute_character_set(translations, i if code in compiled else 0)
                            for i, code in enumerate(languages)]),
    ]:
        lines += ["#[no_mangle]", f"pub static {symbol}: [CStrPtr; {len(languages)}] = ["]
        lines += [f"    CStrPtr({_rust_literal(value, c_string=True)}.as_ptr())," for value in values]
        lines += ["];", ""]

    en_strings = [translations[key][0] for key in string_keys]
    en_offsets: List[int] = []
    for lang_idx, code in enumerate(languages):
        if code not in compiled:
            continue
        offsets: List[int] = []
        blob_strings: List[str] = []
        current_offset = 0
        for i, key in enumerate(string_keys):
            text = translations[key][lang_idx]
            if lang_idx != 0 and text == en_strings[i]:
                offsets.append(en_offsets[i] | 0x8000)
            else:
                offsets.append(current_offset)
                current_offset += len(text.encode("utf-8")) + 1
                blob_strings.append(text)
        if current_offset > 0x7FFF:
            raise ValueError(f"Language {code}: blob size ({current_offset} bytes) exceeds "
                             "15-bit offset limit (32767)")
        if lang_idx == 0:
            en_offsets = list(offsets)
        # C++ appended an implicit terminator after the explicit separators.
        blob = "".join(text + "\0" for text in blob_strings) if blob_strings else "\0"
        lines += [f"static STRINGS_{code}: &[u8] = {_rust_literal(blob)};",
                  f"static OFFSETS_{code}: [u16; STRING_COUNT] = ["]
        for i in range(0, len(offsets), 12):
            lines.append("    " + ", ".join(str(o) for o in offsets[i:i + 12]) + ",")
        lines += ["];", ""]
    lines += ["fn language_strings(language: u8) -> (&'static [u8], &'static [u16]) {",
              "    match language {"]
    for i, code in enumerate(languages):
        if code in compiled and i != 0:
            lines.append(f"        {i} => (STRINGS_{code}, &OFFSETS_{code}),")
    lines += ["        _ => (STRINGS_EN, &OFFSETS_EN),", "    }", "}"]
    _write_file(output_path, lines, verbose)


