#!/usr/bin/env python3
"""Reproduce the MiniBidi tables; do not regenerate from newer Unicode data."""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVISION = '4436ccc228d23f94fd468723c8749607de1b09c4'


def source(name):
    return subprocess.check_output(['git', 'show', f'{REVISION}:lib/MiniBidi/{name}'], cwd=ROOT, text=True)


def clean(text):
    return re.sub(r'/\*.*?\*/', '', text, flags=re.S)


def rows(text):
    return re.findall(r'\{\s*([^{}]+?)\s*\}', clean(text))


out = ['// Generated by test/bidi_diff/generate_tables.py from lib/MiniBidi.',
       '// Original algorithm/data: Ahmad Khalifa and Thomas Wolff (MIT);',
       '// CrossPoint extensions retain the pinned Unicode 17.0.0 data.',
       'use super::*;', '']
for name, filename in [('CLASSES', 'bidiclasses.t'), ('PAIRS', 'bidi_pairs.t')]:
    values = rows(source(filename))
    out.append(f'pub(super) static {name}: &[(u32, u32, u8)] = &[')
    out.extend('    (' + v.replace('BRACKx', '0').replace('BRACKo', '1').replace('BRACKc', '2') + '),' for v in values)
    out.append('];')
src = clean(source('minibidi.c'))
for cname, name, typ in [('shapetypes', 'SHAPES', '(u8, u8)'), ('xjointypes', 'JOINS', '(u32, u32, u8)'), ('xshapeforms', 'FORMS', '(u32, u32, u8)')]:
    body = re.search(r'\b' + cname + r'\[\] = \{(.*?)\};', src, re.S).group(1)
    out.append(f'pub(super) static {name}: &[{typ}] = &[')
    out.extend('    (' + v + '),' for v in rows(body))
    out.append('];')
(ROOT / 'rust/crates/xp-core/src/bidi/tables.rs').write_text('\n'.join(out) + '\n')
