#!/usr/bin/env python3
"""Translate the vendored Expat XML-name bitmap without changing its character set."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[2]
source=(root/'lib/expat/nametab.h').read_text()
license=source[:source.index('*/')+2]
result=[license, '// Generated by test/xml_oracle/name_tables.py from lib/expat/nametab.h.']
for name,rust,ty in [('namingBitmap','BITMAP','u32'),('nmstrtPages','START','u8'),('namePages','CONTINUE','u8')]:
    body=re.search(name+r'\[\]\s*=\s*\{([^}]+)',source).group(1)
    nums=re.findall('0x[0-9a-fA-F]+',body)
    result.append(f'const {rust}: [{ty}; {len(nums)}] = [')
    result.extend('    '+', '.join(nums[i:i+8])+',' for i in range(0,len(nums),8))
    result.append('];')
result.append('''pub(super) fn name(c: char, start: bool) -> bool {
    let cp = c as usize;
    if cp > 0xffff { return false; }
    let pages = if start { &START } else { &CONTINUE };
    BITMAP[usize::from(pages[cp >> 8]) * 8 + ((cp & 255) >> 5)] & (1 << (cp & 31)) != 0
}''')
(root/'rust/crates/xp-core/src/xml/names.rs').write_text('\n'.join(result)+'\n')
