#!/usr/bin/env python3
"""Record/replay compact malformed-token and DTD cases against vendored Expat."""
import argparse
import gzip
import json
from pathlib import Path
import tempfile

from oracle import record

ROOT = Path(__file__).resolve().parent


def cases():
    forms = ("<!-->", "<!--->", "<!---->", "<!-", "<!--", "<![", "<![CDATA[",
             "<?", "<?x", "</", "<!D", "<!DOCTYPE x [", "&#", "&#x", "&#12", "&#x41", "&", "%")
    prefixes = sorted({form[:n] for form in forms for n in range(1, len(form) + 1)})
    for i, form in enumerate(prefixes):
        for context, prefix, suffix in (("prolog", "", ""), ("content", "<r>", ""),
                                        ("subset", "<!DOCTYPE r [", ""),
                                        ("epilog", "<r/>", "")):
            yield f"short_{i}_{context}", prefix + form + suffix
    for i, form in enumerate(("<!-->", "<!--->", "<!---->")):
        yield f"comment_{i}_before", form + "<r/>"
        yield f"comment_{i}_inside", "<r>" + form + "</r>"
        yield f"comment_{i}_after", "<r/>" + form + "x"
    yield "subset_parameter_space", '<!DOCTYPE r [<!ENTITY % p "x"> %p;]><r/>'
    yield "subset_close_space", '<!DOCTYPE r [] ><r/>'
    for i, space in enumerate((" ", "\t", "\r", "\n", " \r\n\t ")):
        yield f"subset_space_{i}", '<!DOCTYPE r [' + space + '<!ENTITY % p "x">' + space + '%p;' + space + ']' + space + '><r/>'
        yield f"subset_close_eof_{i}", '<!DOCTYPE r []' + space
    for code in (0x109, 0x10a, 0x10d, 0x120):
        name = chr(code)
        yield f"entity_unicode_{code}", f'<!DOCTYPE r [<!ENTITY {name} "replacement">]><r a="&{name};">&{name};</r>'
    for kind in ("CDATA", "NMTOKENS"):
        for i, value in enumerate(("<", "a<b", "&lt;", "a&lt;b", "&#60;", "&#x3c;")):
            yield f"default_{kind}_{i}", f'<!DOCTYPE r [<!ATTLIST r a {kind} "{value}">]><r/>'


def encoded_cases():
    for name, text in cases():
        for encoding, bom in (("utf8", b""), ("utf-16le", b"\xff\xfe"),
                              ("utf-16be", b"\xfe\xff")):
            yield name + "_" + encoding, bom + text.encode(encoding)


def rust_fixture(rows):
    kinds = {"start": "Start", "end": "End", "text": "Text", "comment": "Comment",
             "pi": "Pi", "cdata_start": "CdataStart", "cdata_end": "CdataEnd", "entity": "Entity"}
    def string(value):
        return json.dumps(value, ensure_ascii=False).replace(r"\b", r"\u{8}").replace(r"\f", r"\u{c}")
    out = ["// Generated by regressions.py from vendored Expat; do not edit.", "&["]
    for name, source, data in rows:
        used = sorted({index for key, runs in data["schedules"].items()
                       if not key.startswith("stop_") for _, index in runs})
        remap = {old: new for new, old in enumerate(used)}
        out.append("Case { name: " + string(name) + ", input: &[" +
                   ",".join(str(b) for b in bytes.fromhex(source)) + "], variants: &[")
        for index in used:
            v = data["variants"][index]
            out.append("ExpectedRun { events: &[")
            for e in v["events"]:
                out.append("Expected { kind: Kind::" + kinds[e[0]] + ", byte: " + str(e[1]) +
                           ", line: " + str(e[2]) + ", fields: &[" +
                           ",".join(string(x) for x in e[3:]) + "] },")
            out.append("], error: " + str(v["error"]) + ", byte: " + str(v["byte"]) +
                       ", line: " + str(v["line"]) + " },")
        out.append("], splits: &[" + ",".join(f"({count},{remap[index]})" for count, index in
                   data["schedules"]["splits"]) + "], chunks: &[" +
                   ",".join(str(remap[data["schedules"][f"chunks_{n}"][0][1]])
                            for n in (1, 7, 512, 1024)) + "] },")
    return "\n".join(out + ["]", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oracle", type=Path, required=True)
    parser.add_argument("action", choices=("record", "verify"))
    args = parser.parse_args()
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "input.xml"
        for name, data in encoded_cases():
            path.write_bytes(data)
            rows.append([name, data.hex(), record(args.oracle.resolve(), path)])
    golden = ROOT / "regression_goldens.json.gz"
    rust = ROOT / "regression_goldens.rs"
    if args.action == "record":
        golden.write_bytes(gzip.compress(json.dumps(rows, ensure_ascii=False).encode(), mtime=0))
        rust.write_text(rust_fixture(rows))
    else:
        assert rows == json.loads(gzip.decompress(golden.read_bytes())), "Expat regression drift"
        assert rust.read_text() == rust_fixture(rows), "Rust fixture drift"
    schedules = sum(sum(count for count, _ in runs) for _, _, data in rows
                    for runs in data["schedules"].values())
    print(f"{args.action}: {len(rows)} inputs, {schedules} schedules, exact event/status match")


if __name__ == "__main__":
    main()
