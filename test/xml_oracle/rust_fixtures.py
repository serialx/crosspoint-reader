#!/usr/bin/env python3
"""Translate checked-in JSON goldens into dependency-free Rust test data."""
import json
import gzip
from pathlib import Path
ROOT = Path(__file__).resolve().parent
KINDS = {'start':'Start','end':'End','text':'Text','comment':'Comment','pi':'Pi',
         'cdata_start':'CdataStart','cdata_end':'CdataEnd','entity':'Entity'}
def string(s):
    return json.dumps(s,ensure_ascii=False).replace('\\b', '\\u{8}').replace('\\f','\\u{c}')
output=['// Generated by test/xml_oracle/rust_fixtures.py from committed Expat goldens.','&[']
for p in sorted((ROOT/'goldens').glob('*.json.gz')):
    data=json.loads(gzip.decompress(p.read_bytes())); name=p.name[:-8]
    used=sorted({index for key,runs in data['schedules'].items() if not key.startswith('stop_') for _,index in runs})
    remap={old:new for new,old in enumerate(used)}
    output.append('Case { name: '+string(name)+', input: include_bytes!("corpus/'+name+'"), variants: &[')
    for index in used:
        v=data['variants'][index]
        output.append('ExpectedRun { events: &[')
        for e in v['events']:
            output.append('Expected { kind: Kind::'+KINDS[e[0]]+', byte: '+str(e[1])+', line: '+str(e[2])+', fields: &['+','.join(string(x) for x in e[3:])+'] },')
        output.append('], error: '+str(v['error'])+', byte: '+str(v['byte'])+', line: '+str(v['line'])+' },')
    output.append('], splits: &'+'['+','.join(f'({count},{remap[index]})' for count,index in data['schedules']['splits'])+']'+', chunks: &['+','.join(str(remap[data['schedules'][f'chunks_{n}'][0][1]]) for n in (1,7,512,1024))+'] },')
output.append(']')
(ROOT/'rust_goldens.rs').write_text('\n'.join(output)+'\n')
